-- Optional Supabase schema for non-identifying prototype telemetry.
-- Do NOT store raw symptom descriptions or personally identifying health data here.
create table if not exists public.prototype_events (
  id bigint generated by default as identity primary key,
  event_type text not null check (event_type in ('triage_completed', 'triage_failed')),
  care_level text,
  created_at timestamptz not null default now()
);

alter table public.prototype_events enable row level security;

